import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const work = mkdtempSync(join(tmpdir(), 'clif-stubs-'));
const MIN_ZERO_RUN = 64;

function run(command, args) {
  const result = spawnSync(command, args, { stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed`);
}

function assemble(source, target, linkerScript) {
  const object = join(work, `${source}.o`);
  const elf = join(work, `${source}.elf`);
  const bin = join(work, `${source}.bin`);
  run('clang', [`--target=${target}`, '-c', '-o', object, join(here, `${source}.S`)]);
  if (linkerScript) {
    run('ld.lld', ['-T', join(here, linkerScript), '-o', elf, object]);
    run('llvm-objcopy', ['-O', 'binary', elf, bin]);
  } else {
    run('llvm-objcopy', ['-O', 'binary', object, bin]);
  }
  return readFileSync(bin);
}

function chunks(bytes) {
  const out = [];
  let start = null;
  let zeros = 0;
  for (let i = 0; i <= bytes.length; i++) {
    const zero = i < bytes.length && bytes[i] === 0;
    if (i < bytes.length && !zero) {
      start ??= i;
      zeros = 0;
    } else if (start !== null) {
      zeros++;
      if (zeros >= MIN_ZERO_RUN || i === bytes.length) {
        const end = i - zeros + 1;
        out.push([start, Buffer.from(bytes.subarray(start, end)).toString('base64')]);
        start = null;
        zeros = 0;
      }
    }
  }
  return out;
}

const stubs = {
  riscv64: assemble('riscv64', 'riscv64', 'l-riscv64.ld'),
  aarch64: assemble('aarch64', 'aarch64-none-elf', 'l-aarch64.ld'),
  x86_64: assemble('x86_64', 'x86_64-none-elf'),
  s390x: assemble('s390x', 's390x-none-elf', 'l-s390x.ld'),
};

const entries = Object.entries(stubs).map(
  ([arch, bytes]) => `  ${arch}: { size: ${bytes.length}, chunks: ${JSON.stringify(chunks(bytes))} },`,
);
writeFileSync(
  join(here, '..', 'src', 'stubs.mjs'),
  `// generated by web/stubs/build.mjs from the .S files in this directory; do not edit\nexport const STUBS = {\n${entries.join('\n')}\n};\n`,
);
